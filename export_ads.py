def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text.strip() + "\n")


def build_banners(items):
    """Креативы: форматы Авито и Яндекса из одних макетов."""
    used = set()
    made = {"avito": 0, "direct": 0}
    for c in CREATIVES:
        photo = photos_for(c["cat"], items, used)
        for name, size in SIZES.items():
            build(size, c, photo).save(
                os.path.join(ROOT, "Авито", "Баннеры", f'{c["file"]}_{name}.jpg'),
                quality=90, optimize=True)
            made["avito"] += 1
        for name, size in SIZES_DIRECT.items():
            build(size, c, photo).save(
                os.path.join(ROOT, "Яндекс Директ", "Картинки", f'{c["file"]}_{name}.jpg'),
                quality=88, optimize=True)
            made["direct"] += 1
    return made


