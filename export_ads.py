def check(kind, value):
    """Проверяем длину под лимит Яндекса — превышение отклонят на модерации."""
    limit = LIMITS[kind]
    mark = "" if len(value) <= limit else f"  ← ПРЕВЫШЕНИЕ на {len(value) - limit}"
    return f"{value}   [{len(value)}/{limit}]{mark}"


def by_brand(brand, cat, path="data/parts.json"):
    """Сколько позиций марки в категории — как в заголовке страницы каталога."""
    items = json.load(open(path, encoding="utf-8"))["items"]
    brand = brand.upper()
    return sum(1 for i in items
               if i["n"] == cat and brand in [b.upper() for b in i.get("bs") or [i.get("b", "")]])


